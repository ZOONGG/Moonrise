param([string]$JavaHome = 'C:/Program Files/Java/jdk-25.0.3')
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$build = Join-Path $root 'runtime/current-synthetic-adapter'
$loader = Join-Path $env:LOCALAPPDATA 'Moonrise/dev/cache/runtime/weave/weave-loader.jar'
$genesis = Join-Path $env:USERPROFILE '.lunarclient/offline/multiver/genesis-0.1.0-SNAPSHOT-all.jar'
if ((Get-FileHash -LiteralPath $loader).Hash -ne '013B7B9A4CA01A473A1FFC0B031C843C70FE61616E9048FB326E03794C8457B7') { throw 'Untouched Weave 1.3.4 hash mismatch.' }
if ((Get-FileHash -LiteralPath $genesis).Hash -ne 'E3F34C4AD92F1C3BAE83C17BBACB45952C156DF359CB39D6C34D086B05E83C44') { throw 'Untouched Genesis hash mismatch.' }
New-Item -ItemType Directory -Force -Path "$build/classes" | Out-Null
& "$JavaHome/bin/javac.exe" --release 17 -cp "$loader;$genesis" -d "$build/classes" (Get-ChildItem "$PSScriptRoot/current-weave-synthetic/*.java" | ForEach-Object FullName)
if ($LASTEXITCODE) { throw 'Adapter compilation failed.' }
& "$JavaHome/bin/java.exe" -Xverify:all -cp "$build/classes;$loader;$genesis" dev.moonrise.current.SyntheticIntegrationTest $genesis
if ($LASTEXITCODE) { throw 'Synthetic integration check failed.' }
$classNames = @('CurrentSyntheticAgent','SyntheticLoaderMethods','SyntheticLoaderAdapter','SyntheticResolver')
$lines = @('namespace Moonrise.Services;', '// Generated by tools/Build-CurrentWeaveSyntheticAdapter.ps1, Java 17.', 'internal static class CurrentSyntheticAdapterClasses', '{', '    internal static readonly System.Collections.Generic.Dictionary<string, string> Bytes = new()', '    {')
foreach ($name in $classNames) {
    $bytes = [IO.File]::ReadAllBytes("$build/classes/dev/moonrise/current/$name.class")
    $lines += '        ["dev/moonrise/current/' + $name + '.class"] = "' + [Convert]::ToBase64String($bytes) + '",'
}
$lines += '    };', '}'
[IO.File]::WriteAllLines((Join-Path $root 'src/Moonrise/Services/CurrentSyntheticAdapterClasses.cs'), $lines)
Write-Output 'Current synthetic adapter verified and embedded.'
